library(profilemlm)
library(ggplot2)
library(patchwork)
out_dir <- "figures_paper"
dir.create(out_dir, showWarnings = FALSE)
save_fig <- function(p, name, width, height) {                       # PNG for review, PDF for submission
  ggsave(file.path(out_dir, paste0(name, ".png")), p, width = width, height = height, dpi = 300, bg = "white")
  ggsave(file.path(out_dir, paste0(name, ".pdf")), p, width = width, height = height, device = cairo_pdf)
  message("written: ", name)
}
## one theme for all figures: sans serif, light grid, bold panel tags (A, B, ...)
theme_paper <- theme_bw(base_size = 10) +
  theme(panel.grid.minor = element_blank(),
        panel.grid.major = element_line(colour = "grey92", linewidth = 0.3),
        panel.border = element_rect(colour = "grey40", fill = NA, linewidth = 0.4),
        axis.ticks = element_line(colour = "grey40", linewidth = 0.3),
        strip.background = element_rect(fill = "grey95", colour = "grey40", linewidth = 0.4),
        plot.tag = element_text(face = "bold", size = 12),
        legend.position = "bottom", legend.text = element_text(size = 8.5), legend.title = element_text(size = 9))
theme_set(theme_paper)

## ---- Figure 2: simulated example, moderating effects ----------------------
## The three example files shipped with the package (generated by mpa_simulate(),
## seed 2026; see the vignette). The model chain is the one of the vignette and
## the paper: base model without correlations, pruned where singular, the pruned
## structure carried through Steps 2-4.
ex <- function(f) system.file("extdata", f, package = "profilemlm")
perceiver_survey <- read.csv(ex("perceiver_survey.csv"))
target_survey    <- read.csv(ex("target_survey.csv"))
items            <- read.csv(ex("items.csv"))
dat <- mpa_data(judgments = perceiver_survey, format = "loop", loop_id = "id",
              targets = target_survey, items = items, item_cols = "^item_",
              criterion = list(self = "targets"), group = "group",
              rating_scale = c(1, 101), norm = "loo", verbose = FALSE)

## ---- Figure 1: design and model ----------------------------------------------
dd <- as.data.frame(dat)
dd$N <- dd$self.norm                      # normative profile on the rating scale
dd$C <- dd$self.norm + dd$self.dist * 50  # criterion (self-rating): components are stored per half scale range
dd$D <- dd$C - dd$N

## The dyad of Panels B-D: within-dyad regression of J on N and D (ordinary least squares,
## which is what the mixed model estimates for every dyad with shrinkage). Chosen for clear,
## above-average slopes; Panel A is then drawn around this dyad and outlines it.
per_dyad <- do.call(rbind, lapply(split(dd, list(dd$perceiver, dd$target), drop = TRUE), function(x) {
  cf <- coef(lm(y ~ N + D, data = x))
  data.frame(perceiver = x$perceiver[1], target = x$target[1], b0 = cf[1], b1 = cf[2], b2 = cf[3],
             r2 = summary(lm(y ~ N + D, data = x))$r.squared)
}))
cand <- per_dyad[per_dyad$b1 > 0.7 & per_dyad$b1 < 0.9 & per_dyad$b2 > 0.35 & per_dyad$b2 < 0.5, ]
pick <- cand[which.max(cand$r2), ]
b <- dd[dd$perceiver == pick$perceiver & dd$target == pick$target, ]
b <- b[order(b$N), ]; b$pos <- seq_len(nrow(b))
cf <- coef(lm(y ~ N + D, data = b)); names(cf) <- c("b0", "b1", "b2")
message(sprintf("Figure 1 dyad: %s judging %s; b0 = %.1f, b1 = %.2f, b2 = %.2f", pick$perceiver, pick$target, cf[1], cf[2], cf[3]))
## Panel A window: four perceivers and four targets of the picked dyad's group (left block) and of the
## next group (right block); the picked dyad is in the left block
pnum <- function(x) as.integer(sub("^[pt]", "", x))
g_pick <- (pnum(pick$perceiver) - 1) %/% 8 + 1; g_next <- if (g_pick < 6) g_pick + 1 else 1
win <- function(id, g) { k <- (pnum(id) - 1) %% 8 + 1; st <- if (k <= 4) 1 else 5; (g - 1) * 8 + st:(st + 3) }
pA_ids <- list(p = sprintf("p%03d", c(win(pick$perceiver, g_pick), (g_next - 1) * 8 + 1:4)),
               t = sprintf("t%03d", c(win(pick$target, g_pick), (g_next - 1) * 8 + 1:4)))
pick_pi <- match(pick$perceiver, pA_ids$p); pick_ti <- match(pick$target, pA_ids$t)   # its cell in Panel A

## Panel A: two groups of four perceivers and four targets, eight items; one profile per dyad
items8 <- paste0("item_", sprintf("%02d", 1:8))
a <- dd[dd$perceiver %in% pA_ids$p & dd$target %in% pA_ids$t & dd$item %in% items8, ]
a$pi <- match(a$perceiver, pA_ids$p); a$ti <- match(a$target, pA_ids$t)
a$x <- a$ti + (match(a$item, items8) - 1) / 7 * 0.76 - 0.38
a$yy <- a$pi + 0.38 - (a$y - 1) / 100 * 0.76        # y reversed: perceiver 1 at the top
cells <- expand.grid(pi = 1:8, ti = 1:8); cells$judged <- ((cells$pi - 1) %/% 4) == ((cells$ti - 1) %/% 4)

pA <- ggplot() +
  geom_tile(data = cells, aes(ti, pi, fill = judged), colour = "grey75", linewidth = 0.3, width = 1, height = 1) +
  scale_fill_manual(values = c(`TRUE` = "grey92", `FALSE` = "white"), guide = "none") +
  geom_path(data = a, aes(x, yy, group = interaction(perceiver, target)), colour = "grey15", linewidth = 0.35) +
  annotate("rect", xmin = pick_ti - 0.5, xmax = pick_ti + 0.5, ymin = pick_pi - 0.5, ymax = pick_pi + 0.5, fill = NA, colour = "black", linewidth = 0.8) +
  annotate("text", x = 6.5, y = pick_pi - 0.25, label = "one dyad:\none profile\nacross items\n(Panels B\u2013D)", size = 2.9, lineheight = 0.9) +
  annotate("segment", x = 5.35, xend = pick_ti + 0.6, y = pick_pi, yend = pick_pi, arrow = arrow(length = unit(0.15, "cm")), linewidth = 0.4) +
  annotate("text", x = 2.5, y = 6.5, label = "not judged", size = 2.9, colour = "grey55") +
  annotate("text", x = 6.5, y = 6.5, label = "", size = 2.9) +
  scale_x_continuous(breaks = 1:8, labels = paste0("T", 1:8), expand = c(0, 0), position = "top",
                     sec.axis = dup_axis(name = NULL, labels = NULL)) +
  scale_y_reverse(breaks = 1:8, labels = paste0("P", 1:8), expand = c(0, 0)) +
  coord_fixed(clip = "off") +
  labs(x = "Targets (T1\u2013T4 one group, T5\u2013T8 another)", y = "Perceivers (P1\u2013P4 one group, P5\u2013P8 another)") +
  theme(panel.grid = element_blank(), axis.ticks = element_blank(), panel.border = element_blank(),
        axis.text = element_text(size = 8), plot.margin = margin(6, 6, 6, 6))

lev <- c("Normative profile N", "Criterion profile C (self-ratings)", "Judgments J")
b_long <- rbind(data.frame(pos = b$pos, value = b$N, what = lev[1]),
                data.frame(pos = b$pos, value = b$C, what = lev[2]),
                data.frame(pos = b$pos, value = b$y, what = lev[3]))
b_long$what <- factor(b_long$what, levels = lev)
pB <- ggplot() +
  geom_segment(data = b, aes(x = pos, xend = pos, y = N, yend = C), colour = "grey40", linewidth = 0.9) +
  geom_line(data = b_long, aes(pos, value, colour = what, linetype = what, linewidth = what)) +
  geom_point(data = b_long[b_long$what == lev[3], ], aes(pos, value), size = 1.4) +
  scale_colour_manual(values = c("grey60", "grey25", "black"), name = NULL) +
  scale_linetype_manual(values = c("solid", "22", "solid"), name = NULL) +
  scale_linewidth_manual(values = c(1.8, 0.55, 0.45), name = NULL) +
  annotate("text", x = 1.5, y = 95, label = "D = C \u2212 N (grey segments)", size = 3, hjust = 0) +
  scale_x_continuous(breaks = c(1, 10, 20, 30)) + coord_cartesian(ylim = c(1, 101)) +
  labs(x = "Items, ordered by the normative profile", y = "Rating (1\u2013101)") +
  theme(legend.key.width = unit(1.3, "cm"), legend.margin = margin(0, 0, 0, 0))

## Panels C and D: the dyad-specific slopes b1 and b2 of Equation 1, estimated by OLS within this
## one dyad (in the mixed model they are gamma + u + v + w, not parameters; the caption says so)
slope_panel <- function(xvar, slope, xlab, lab) {
  xm <- mean(b[[xvar]]); ym <- mean(b$y)
  ggplot(b, aes(.data[[xvar]], y)) +
    geom_abline(intercept = ym - slope * xm, slope = slope, colour = "grey30", linewidth = 0.6) +
    geom_point(size = 1.4) +
    annotate("text", x = -Inf, y = Inf, label = lab, hjust = -0.1, vjust = 1.5, size = 3.2, parse = TRUE) +
    labs(x = xlab, y = expression(Judgment~italic(J)))
}
pC1 <- slope_panel("N", cf[["b1"]], expression(Normative~profile~italic(N)),
                   sprintf("italic(b)[1]~'= %.2f (normative agreement)'", cf[["b1"]]))
pC2 <- slope_panel("D", cf[["b2"]], expression(Distinctive~profile~italic(D)),
                   sprintf("italic(b)[2]~'= %.2f (distinctive agreement)'", cf[["b2"]]))
fig1 <- (pA | pB) / (pC1 | pC2) + plot_layout(heights = c(2.2, 1.3)) + plot_annotation(tag_levels = "A")
save_fig(fig1, "figure1_design_model", width = 10.5, height = 7.4)

f1 <- mpa_formula(dat, criterion = "self")
f_base <- mpa_update(f1, correlated = FALSE)
m_base <- mpa_fit(f_base, dat)
if (m_base$singular) { f_base <- mpa_prune(m_base); m_base <- mpa_fit(f_base, dat) }
f2 <- mpa_formula(dat, criterion = "self", random_slopes = "des", random_structure = f_base)
m2 <- mpa_fit(f2, dat)
if (m2$singular) { f_base <- mpa_prune(m2); m2 <- mpa_fit(f_base, dat) }
f3 <- mpa_formula(dat, criterion = "self", random_slopes = "des", poly = "des",
                  interactions = "criterion", random_structure = f_base)
m3s <- mpa_fit(f3, dat, start_from = m2)
f4 <- mpa_formula(dat, criterion = "self", random_slopes = "des", poly = "des",
                  predictors = c("know", "training", "talkativeness"),
                  interactions = "criterion", random_structure = f_base)
m4 <- mpa_fit(f4, dat, start_from = m3s)

labels <- c(des = "Item desirability", know = "Acquaintance", training = "Perceiver training",
            talkativeness = "Target talkativeness", self.dist = "Distinctive agreement", self.norm.c = "Normative agreement")
p4 <- mpa_plots(m4, labels = labels)                                  # common y-axis per slope
p4 <- lapply(p4, function(p) p + labs(y = "Distinctive agreement\n(slope per criterion point)") +
               scale_x_continuous(breaks = c(-1, -0.5, 0, 0.5, 1)))
fig2 <- (p4[["self.dist_by_des"]] + p4[["self.dist_by_know"]] +
         p4[["self.dist_by_training"]] + p4[["self.dist_by_talkativeness"]]) +
        plot_layout(nrow = 1, axes = "collect") + plot_annotation(tag_levels = "A") & theme_paper
save_fig(fig2, "figure2_simulated_example", width = 10, height = 3.2)

